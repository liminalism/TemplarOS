#!/usr/bin/env bash
# Compose mkosi.conf.d/50-seeds.conf from ../seeds/*.seed and render os-release into mkosi.extra.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
seeds="$here/../seeds"
out="$here/mkosi.conf.d/50-seeds.conf"
{
  echo "# GENERATED by compose.sh from distro/seeds — do not edit."
  echo "[Content]"
  echo "Packages="
  for seed in minimal session desktop hardware ime a11y; do
    grep -vE '^\s*(#|$)' "$seeds/$seed.seed" | sed 's/^/        /'
  done
} > "$out"
mkdir -p "$here/mkosi.extra/usr/lib"
cp "$here/../branding/os-release" "$here/mkosi.extra/usr/lib/os-release.legeos"
echo "composed $out"
