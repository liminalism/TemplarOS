#!/usr/bin/env bash
# Compose the image's generated inputs, then hand over to mkosi.
#
#   * the package drop-ins and every other seed artifact, from distro/seeds/selection.toml
#     (`cargo xtask seeds` — one declaration, so the image list cannot drift from the metapackages);
#   * mkosi.extra/usr/lib/os-release.templaros, from distro/branding/os-release;
#   * mkosi.conf.d/40-local-archive.conf, but only when a local TemplarOS build set is actually named.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"

cargo run -q -p xtask --manifest-path "$root/Cargo.toml" -- seeds

mkdir -p "$here/mkosi.extra/usr/lib"
cp "$here/../branding/os-release" "$here/mkosi.extra/usr/lib/os-release.templaros"

# Build from one named TemplarOS build set (C2, D2). $TEMPLAROS_BUILD_SET wins; otherwise the archive's
# `current` marker, if it exists. With neither, no drop-in is written at all — an image built from
# the plain Ubuntu archive is a legitimate thing to want, and a stale pin to a set that has been
# pruned is not.
archive="${TEMPLAROS_DEVREPO:-/var/lib/templaros/devrepo}"
drop_in="$here/mkosi.conf.d/40-local-archive.conf"
set_id="${TEMPLAROS_BUILD_SET:-}"
if [ -z "$set_id" ] && [ -r "$archive/current" ]; then
  set_id="$(cat "$archive/current")"
fi
if [ -n "$set_id" ] && [ -d "$archive/sets/$set_id/debs" ]; then
  cat > "$drop_in" <<EOF
# GENERATED by compose.sh — do not edit. Build the image from one named local TemplarOS build set.
[Distribution]
PackageDirectories=$archive/sets/$set_id/debs
EOF
  echo "composed $drop_in (build set $set_id)"
else
  rm -f "$drop_in"
  [ -n "$set_id" ] && echo "compose: build set $set_id has no debs under $archive/sets — no local archive drop-in"
fi

echo "composed $here/mkosi.conf.d/50-seeds.conf"
