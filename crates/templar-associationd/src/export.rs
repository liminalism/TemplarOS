//! Compatibility export to `mimeapps.list`.
//!
//! `associationd` owns this file. During migration, existing settings are imported once,
//! conflicts shown, and the file is then generated atomically. Five settings applications
//! must not rewrite it independently.

use crate::engine::AssociationDb;
use anyhow::{Context, Result, bail};
use std::{
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};
use templar_types::AppCatalog;

/// Render the `mimeapps.list` text for `db`.
pub fn render_mimeapps(db: &AssociationDb, catalog: &dyn AppCatalog) -> Result<String> {
    // Match the owned resolver's alias/sibling policy. An absent or no-longer-capable copy is
    // omitted from the compatibility view without deleting the person's durable selection.
    let selected: Vec<_> = db.mime_defaults.iter().filter_map(|(mime, stored)| {
        let resolved = crate::engine::live_handler(catalog, stored, |id| {
            catalog.manifest(id).is_some_and(|manifest| manifest.supports_mime(mime))
        })?;
        Some((mime, catalog.manifest(&resolved.app_id)?))
    }).collect();
    let mut output = String::new();
    output.push_str(
        "# Generated by TemplarOS associationd. Use System Settings or `templar open` to edit.\n\n",
    );
    output.push_str("[Default Applications]\n");

    for (mime, manifest) in &selected {
        validate_desktop_id(&manifest.primary_desktop_file_id)?;
        writeln!(output, "{mime}={};", manifest.primary_desktop_file_id)?;
    }

    output.push_str("\n[Added Associations]\n");
    // Adding the same desktop entry here ensures each selected default is also registered as
    // supporting the MIME type, as the mime-apps spec requires.
    for (mime, manifest) in &selected {
        writeln!(output, "{mime}={};", manifest.primary_desktop_file_id)?;
    }

    Ok(output)
}

/// Render and atomically write `mimeapps.list` to `destination`.
pub fn export_mimeapps(
    db: &AssociationDb,
    catalog: &dyn AppCatalog,
    destination: &Path,
) -> Result<()> {
    let output = render_mimeapps(db, catalog)?;
    atomic_write(destination, output.as_bytes())
}

fn validate_desktop_id(value: &str) -> Result<()> {
    let valid = value.ends_with(".desktop") && !value.contains(['\n', '\r', ';', '=']);
    if !valid {
        bail!("invalid desktop file ID: {value:?}");
    }
    Ok(())
}

pub(crate) fn atomic_write(destination: &Path, contents: &[u8]) -> Result<()> {
    let parent = destination
        .parent()
        .context("destination has no parent directory")?;
    fs::create_dir_all(parent)?;
    let temporary = temporary_path(destination);
    fs::write(&temporary, contents)?;
    // Rename is atomic when the temporary and destination files are on the same filesystem.
    fs::rename(&temporary, destination)?;
    Ok(())
}

fn temporary_path(destination: &Path) -> PathBuf {
    let mut temporary = destination.as_os_str().to_owned();
    temporary.push(format!(".tmp-{}", std::process::id()));
    PathBuf::from(temporary)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::tests::StaticCatalog;
    use templar_types::AppId;

    #[test]
    fn export_writes_both_sections_atomically() {
        let catalog = StaticCatalog::with(&[("org.templaros.Viewer", &["application/pdf"])]);
        let mut db = AssociationDb::default();
        db.mime_defaults.insert(
            "application/pdf".into(),
            "org.templaros.Viewer".parse::<AppId>().unwrap(),
        );

        let dir = tempfile::tempdir().unwrap();
        let destination = dir.path().join("nested").join("mimeapps.list");
        export_mimeapps(&db, &*catalog, &destination).unwrap();

        let text = fs::read_to_string(&destination).unwrap();
        assert!(
            text.contains("[Default Applications]\napplication/pdf=org.templaros.Viewer.desktop;")
        );
        assert!(
            text.contains("[Added Associations]\napplication/pdf=org.templaros.Viewer.desktop;")
        );
        assert!(
            fs::read_dir(destination.parent().unwrap()).unwrap().count() == 1,
            "no temp file left behind"
        );
    }
}
